import json

import numpy as np

from tissue_patch_eval.data import PatchData
from tissue_patch_eval.pipeline import run_pipeline, verify_report


def test_real_pipeline_writes_readable_and_auditable_artifacts(tmp_path):
    rng = np.random.default_rng(5)
    n = 48
    labels = np.tile([0, 1], n // 2)
    images = rng.integers(40, 220, size=(n, 96, 96, 3), dtype=np.uint8)
    slides = np.repeat([f"fixture_slide_{i}" for i in range(8)], 6)
    rows = [{"coord_x": str(i * 96), "coord_y": "0"} for i in range(n)]
    data = PatchData(images, labels, slides, rows)
    run_pipeline(
        data,
        tmp_path,
        {"source": "Synthetic test fixture, not public-data results"},
        folds=2,
        trees=8,
        bootstrap=20,
    )
    assert b"\r" not in (tmp_path / "predictions.csv").read_bytes()
    report = json.loads((tmp_path / "results.json").read_text())
    assert report["dataset"]["patches"] == n
    assert report["dataset"]["slides"] == 8
    assert report["dataset"]["source"] == "Synthetic test fixture, not public-data results"
    assert (tmp_path / "report.md").read_text().startswith("# Tissue patch evaluation")
    html = (tmp_path / "report.html").read_text()
    assert "data:image/png;base64," in html
    assert "not a diagnostic tool" in html
    assert 'src="http' not in html
    assert report["stress"]["blur"]["n"] > 0
    assert report["stress"]["pen"]["flagged_fraction"] == 1
    verify_report(tmp_path)
    # A changed prediction must not silently retain the old published metrics.
    with (tmp_path / "predictions.csv").open("a") as f:
        f.write("tampered\n")
    import pytest

    with pytest.raises(ValueError, match="checksum"):
        verify_report(tmp_path)


def test_saved_metric_comparison_allows_only_rounding_precision():
    from tissue_patch_eval.pipeline import statistics_equal

    assert statistics_equal({"score": [0.8, None]}, {"score": [0.8 + 1e-15, None]})
    assert not statistics_equal({"score": [0.8]}, {"score": [0.81]})
    assert not statistics_equal({"n": 4}, {"n": 5})
    assert not statistics_equal({"score": None}, {"score": 0})


def test_report_replay_rejects_stale_readable_output(tmp_path):
    from tissue_patch_eval.pipeline import verify_readable_report
    from tissue_patch_eval.report import write_report

    # This guard operates on generated bytes and does not need data or model fitting.
    # Use the complete fixture output generated by the integration test shape.
    rng = np.random.default_rng(1)
    n = 24
    data = PatchData(
        rng.integers(40, 200, (n, 96, 96, 3), dtype=np.uint8),
        np.tile([0, 1], n // 2),
        np.repeat(["a", "b", "c", "d"], 6),
        [{"coord_x": str(i), "coord_y": "0"} for i in range(n)],
    )
    r = run_pipeline(
        data, tmp_path, {"source": "Synthetic test fixture"}, folds=2, trees=4, bootstrap=20
    )
    verify_readable_report(r, tmp_path)
    (tmp_path / "report.md").write_text("outdated numbers")
    import pytest

    with pytest.raises(ValueError, match="stale"):
        verify_readable_report(r, tmp_path)
    write_report(r, tmp_path)
    verify_readable_report(r, tmp_path)


def test_audit_replay_rejects_changed_counts_folds_and_example_captions(tmp_path):
    import copy
    import csv

    import pytest

    from tissue_patch_eval.audit import verify_evidence

    rng = np.random.default_rng(2)
    n = 24
    data = PatchData(
        rng.integers(40, 200, (n, 96, 96, 3), dtype=np.uint8),
        np.tile([0, 1], n // 2),
        np.repeat(["a", "b", "c", "d"], 6),
        [{"coord_x": str(i), "coord_y": "0"} for i in range(n)],
    )
    result = run_pipeline(
        data, tmp_path, {"source": "Synthetic test fixture"}, folds=2, trees=4, bootstrap=20
    )
    with (tmp_path / "predictions.csv").open() as f:
        rows = list(csv.DictReader(f))
    verify_evidence(result, rows, tmp_path)
    mutations = [
        lambda r: r["dataset"].update(positives=999999),
        lambda r: r["dataset"].update(duplicate_image_rows=999),
        lambda r: r["fold_audit"]["slide"][0].update(train_n=999999),
        lambda r: r["fold_audit"]["slide"][0].update(train_positive_fraction=0.99),
        lambda r: r["fold_audit"]["slide"][0].update(overlap_image_hashes=123),
        lambda r: r["examples"][0].update(label=1 - r["examples"][0]["label"]),
        lambda r: r["fold_audit"].update(slide=[]),
        lambda r: r["fold_audit"]["slide"][1].update(fold=0),
    ]
    for mutate in mutations:
        changed = copy.deepcopy(result)
        mutate(changed)
        with pytest.raises(ValueError):
            verify_evidence(changed, rows, tmp_path)
